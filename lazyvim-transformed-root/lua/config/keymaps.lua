-- On Lua filetype detection, add a buffer-local mapping to execute Lua through
-- Snacks.debug.run; ft is not an option accepted by vim.keymap.set.
vim.api.nvim_create_autocmd("FileType", {
  group = vim.api.nvim_create_augroup("config_lua_keymaps", { clear = true }),
  pattern = "lua",
  callback = function(event)
    map({ "n", "x" }, "<localleader>r", function() Snacks.debug.run() end,
      { desc = "Run Lua", buffer = event.buf })
  end,
})
